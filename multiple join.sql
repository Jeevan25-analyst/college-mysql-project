-- MULTIPLE JOIN
use sakila;
-- 1.Find the first name of customers and the movies they rented.
select * from customer;
select * from rental;
select * from inventory;
select * from film;
select c.first_name,f.title from customer c join rental r on c.customer_id = r.customer_id join inventory i on r.inventory_id = i.inventory_id 
join film f on i.film_id = f.film_id;

-- 2.Find total amount spent by each customer.alter
select * from customer;
select * from payment;
select c.customer_id,c.first_name,c.last_name,SUM(p.amount) as total_spent FROM customer c JOIN payment p ON c.customer_id = p.customer_id
GROUP BY c.customer_id, c.first_name, c.last_name ORDER BY total_spent DESC;

-- 3.Find top 5 customers who spent the most money.
select * from film;
select * from inventory;
select * from rental;
SELECT c.customer_id,c.first_name,c.last_name,SUM(p.amount) AS total_spent FROM customer c JOIN payment p ON c.customer_id = p.customer_id
 GROUP BY c.customer_id, c.first_name, c.last_name ORDER BY total_spent DESC LIMIT 5;
 
-- 4.Find how many times each movie was rented.
select * from film;
select * from inventory;
select * from rental;
SELECT f.film_id,f.title,COUNT(r.rental_id) AS times_rented FROM film f JOIN inventory i ON f.film_id = i.film_id JOIN rental r 
ON i.inventory_id = r.inventory_id GROUP BY f.film_id, f.title ORDER BY times_rented DESC;

-- 5.Find the revenue generated by each film category. 
select * from category;
select * from film_category;
select * from film;
select * from inventory;
select * from rental;
select * from payment;
SELECT c.name AS category,SUM(p.amount) AS total_revenue FROM category c JOIN film_category fc ON c.category_id = fc.category_id 
JOIN inventory i ON fc.film_id = i.film_id JOIN rental r ON i.inventory_id = r.inventory_id JOIN payment p ON r.rental_id = p.rental_id 
GROUP BY c.category_id, c.name ORDER BY total_revenue DESC;
-- 6.Find actors who acted in each film. 
select * from actor;
select * from film_actor;
select * from film;
SELECT f.title AS film,CONCAT(a.first_name, ' ', a.last_name) AS actor FROM film f JOIN film_actor fa ON f.film_id = fa.film_id 
JOIN actor a ON fa.actor_id = a.actor_id ORDER BY f.title, actor;

-- 7.Find which store generated the highest revenue. 
select * from store;
select * from staff;
select * from payment;
SELECT s.store_id,SUM(p.amount) AS total_revenue FROM store s JOIN staff st ON s.store_id = st.store_id JOIN payment p 
ON st.staff_id = p.staff_id GROUP BY s.store_id ORDER BY total_revenue DESC LIMIT 1;

-- 8.Find the monthly revenue from rentals.
select * from payment;
SELECT YEAR(payment_date) AS year,MONTHNAME(payment_date) AS month,SUM(amount) AS monthly_revenue FROM payment 
GROUP BY YEAR(payment_date), MONTH(payment_date), MONTHNAME(payment_date)ORDER BY year, MONTH(payment_date);

-- 9.Find the average payment made by customers.
select * from payment;
SELECT customer_id,AVG(amount) AS average_payment FROM payment GROUP BY customer_id ORDER BY average_payment DESC;

-- 10.Find the top 5 most rented film categories.
select * from category;
select * from film_category;
select * from film;
select * from inventory;
select * from rental;
SELECT c.name AS category,COUNT(r.rental_id) AS total_rentals FROM category c JOIN film_category fc ON c.category_id = fc.category_id 
JOIN film f ON fc.film_id = f.film_id JOIN inventory i ON f.film_id = i.film_id JOIN rental r ON i.inventory_id = r.inventory_id
 GROUP BY c.category_id, c.name ORDER BY total_rentals DESC LIMIT 5;
 
